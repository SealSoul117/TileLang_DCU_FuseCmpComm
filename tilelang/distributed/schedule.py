"""Pure-Python mapping for the DCU direct-push owner-reduce schedule.

The scheduling formulas mirror ``fused_gemm_allreduce_v1.hip``.  In
particular, binary ready flags are addressed by a *producer work batch start*,
not by an arbitrary consumer tile.  For row-major AllReduce work IDs happen to
equal tile IDs; retaining the ``*_work`` name prevents that coincidence from
silently becoming an invalid ReduceScatter formula.
"""

from __future__ import annotations

from dataclasses import dataclass
import json
from typing import Any, Iterator, Mapping, Optional, Tuple

from .spec import DistributedConfigError, FusionSpec, _is_int, _parse_json, _strict_object


def _fail(message: str) -> None:
    raise DistributedConfigError(message)


@dataclass(frozen=True)
class ProducerAssignment:
    """One active compute work item and the v1 batch that publishes it."""

    work_id: int
    tile_id: int
    bx: int
    by: int
    owner: int
    owned_index: int
    owner_slot: int
    producer_block: int
    producer_iteration: int
    batch_start_work: int


@dataclass(frozen=True)
class ReadyKey:
    """A v1 binary ready location on ``owner``'s symmetric ready allocation.

    ``batch_start_work`` is the batch start generated by the producer block:
    ``block + floor(iteration / batch_tiles) * batch_tiles * compute_blocks``.
    Its local ready-array offset is ``batch_start_work * nranks + source``.
    ``owner`` selects the remote ready allocation and is deliberately not added
    to that local offset.
    """

    owner: int
    batch_start_work: int
    source: int
    storage_index: int


@dataclass(frozen=True)
class ConsumerAssignment:
    """One active owner-local consumer slot, independent of compute work IDs."""

    owner: int
    owned_index: int
    tile_id: int
    comm_lane: int
    consumer_iteration: int


@dataclass(frozen=True)
class SchedulePlan:
    """Validated mapping shared by producer and consumer lowering.

    ``work_id`` is a logical compute-order position.  It is mapped to a tile
    before ownership is evaluated.  ``consumer_tile_order`` is separately
    derived from owner-local tile lists.  This distinction matters for
    ReduceScatter: its contiguous-row ownership has a deliberately
    owner-interleaved consumer order and must never use a work ID as an owned
    tile index.
    """

    spec: FusionSpec
    compute_blocks: int

    def __post_init__(self) -> None:
        if not isinstance(self.spec, FusionSpec):
            _fail("SchedulePlan spec must be a FusionSpec")
        if not _is_int(self.compute_blocks) or self.compute_blocks <= 0:
            _fail("compute_blocks must be a positive integer")

    @property
    def tiles_x(self) -> int:
        return (self.spec.n + self.spec.tile_n - 1) // self.spec.tile_n

    @property
    def tiles_y(self) -> int:
        return (self.spec.m + self.spec.tile_m - 1) // self.spec.tile_m

    @property
    def tile_count(self) -> int:
        return self.tiles_x * self.tiles_y

    @property
    def grid_blocks(self) -> int:
        return self.compute_blocks + self.spec.comm_blocks

    @property
    def tile_elements(self) -> int:
        return self.spec.tile_m * self.spec.tile_n

    def _check_tile(self, tile_id: int) -> None:
        if not _is_int(tile_id) or not 0 <= tile_id < self.tile_count:
            _fail(f"tile_id must satisfy 0 <= tile_id < {self.tile_count}")

    def _check_work(self, work_id: int) -> None:
        if not _is_int(work_id) or not 0 <= work_id < self.tile_count:
            _fail(f"work_id must satisfy 0 <= work_id < {self.tile_count}")

    def _check_rank(self, rank: int) -> None:
        if not _is_int(rank) or not 0 <= rank < self.spec.nranks:
            _fail(f"rank must satisfy 0 <= rank < {self.spec.nranks}")

    def work_to_tile(self, work_id: int) -> int:
        """Return the tile for a logical compute work item in the required order."""
        self._check_work(work_id)
        if self.spec.compute_tile_order == "row_major":
            return work_id
        return self._owner_interleaved_tiles()[work_id]

    def tile_to_work(self, tile_id: int) -> int:
        self._check_tile(tile_id)
        if self.spec.compute_tile_order == "row_major":
            return tile_id
        return self._owner_interleaved_tiles().index(tile_id)

    def tile_to_coords(self, tile_id: int) -> Tuple[int, int]:
        self._check_tile(tile_id)
        return tile_id % self.tiles_x, tile_id // self.tiles_x

    def coords_to_tile(self, bx: int, by: int) -> int:
        """Inverse of :meth:`tile_to_coords` for logical tile coordinates."""
        if not _is_int(bx) or not 0 <= bx < self.tiles_x:
            _fail(f"bx must satisfy 0 <= bx < {self.tiles_x}")
        if not _is_int(by) or not 0 <= by < self.tiles_y:
            _fail(f"by must satisfy 0 <= by < {self.tiles_y}")
        return by * self.tiles_x + bx

    def tile_extent(self, tile_id: int) -> Tuple[int, int]:
        """Valid (rows, columns) for a tile in the mapping-only edge model.

        A later lowering must either implement these guards or reject the spec
        through ``FusionSpec.validate_v1_lowering``; M0 does not claim GPU edge
        tiles execute today.
        """
        bx, by = self.tile_to_coords(tile_id)
        return min(self.spec.tile_m, self.spec.m - by * self.spec.tile_m), min(
            self.spec.tile_n, self.spec.n - bx * self.spec.tile_n
        )

    def tile_is_full(self, tile_id: int) -> bool:
        return self.tile_extent(tile_id) == self.spec.tile_shape

    def owner_of_tile(self, tile_id: int) -> int:
        self._check_tile(tile_id)
        if self.spec.owner_policy == "cyclic":
            return tile_id % self.spec.nranks
        # Standard quotient/remainder partition gives contiguous logical row
        # ranges.  Some ranks own zero rows when tiles_y < nranks; they are
        # inactive consumers, rather than receiving a fake tile/slot.
        _, by = self.tile_to_coords(tile_id)
        base, extra = divmod(self.tiles_y, self.spec.nranks)
        split = (base + 1) * extra
        if by < split:
            return by // (base + 1)
        if base == 0:
            _fail("internal row-owner error for zero-sized contiguous partition")
        return extra + (by - split) // base

    def owner_tiles(self, owner: int) -> Tuple[int, ...]:
        self._check_rank(owner)
        return tuple(tile_id for tile_id in range(self.tile_count) if self.owner_of_tile(tile_id) == owner)

    def owned_tile_count(self, owner: int) -> int:
        return len(self.owner_tiles(owner))

    def owned_index(self, tile_id: int) -> int:
        self._check_tile(tile_id)
        owner = self.owner_of_tile(tile_id)
        if self.spec.owner_policy == "cyclic":
            # Exact v1 formula for allreduce cyclic ownership.
            return tile_id // self.spec.nranks
        # RS rows are contiguous, but a row contains tiles_x tiles.  This is a
        # local ordinal in the owner's tile list, never a producer work ID.
        tiles = self.owner_tiles(owner)
        return tiles.index(tile_id)

    def tile_from_owned_index(self, owner: int, owned_index: int) -> Optional[int]:
        """Return an owned tile, or None for an inactive/tail consumer slot."""
        self._check_rank(owner)
        if not _is_int(owned_index) or owned_index < 0:
            _fail("owned_index must be a non-negative integer")
        tiles = self.owner_tiles(owner)
        return tiles[owned_index] if owned_index < len(tiles) else None

    def output_tile_to_local_offset(self, tile_id: int, rank: int) -> Optional[int]:
        """Map physical tile-major output to the rank-local output workspace.

        AllReduce materializes every tile on every PE, so its local offset is
        the global tile ID.  ReduceScatter has a symmetric maximum-sized output
        allocation, but only ``owned_tile_count(rank)`` entries are valid; a
        non-owned tile returns ``None`` instead of inventing a slot.
        """
        self._check_tile(tile_id)
        self._check_rank(rank)
        if self.spec.collective_kind == "allreduce":
            return tile_id
        if self.owner_of_tile(tile_id) != rank:
            return None
        return self.owned_index(tile_id)

    def output_valid_tile_count(self, rank: int) -> int:
        self._check_rank(rank)
        return self.tile_count if self.spec.collective_kind == "allreduce" else self.owned_tile_count(rank)

    def owner_slot(self, tile_id: int, source: int) -> int:
        self._check_tile(tile_id)
        self._check_rank(source)
        return self.owned_index(tile_id) * self.spec.nranks + source

    def producer_for_work(self, work_id: int, source: int) -> ProducerAssignment:
        self._check_work(work_id)
        self._check_rank(source)
        tile_id = self.work_to_tile(work_id)
        producer_block = work_id % self.compute_blocks
        producer_iteration = work_id // self.compute_blocks
        batch_first_iteration = (producer_iteration // self.spec.batch_tiles) * self.spec.batch_tiles
        batch_start_work = producer_block + batch_first_iteration * self.compute_blocks
        bx, by = self.tile_to_coords(tile_id)
        owner = self.owner_of_tile(tile_id)
        owned_index = self.owned_index(tile_id)
        return ProducerAssignment(
            work_id=work_id,
            tile_id=tile_id,
            bx=bx,
            by=by,
            owner=owner,
            owned_index=owned_index,
            owner_slot=self.owner_slot(tile_id, source),
            producer_block=producer_block,
            producer_iteration=producer_iteration,
            batch_start_work=batch_start_work,
        )

    def producer_for_tile(self, tile_id: int, source: int) -> ProducerAssignment:
        return self.producer_for_work(self.tile_to_work(tile_id), source)

    def batch_work_items(self, producer_block: int, batch_start_work: int) -> Tuple[int, ...]:
        """Active work IDs in one physical producer batch, with the tail guarded."""
        if not _is_int(producer_block) or not 0 <= producer_block < self.compute_blocks:
            _fail(f"producer_block must satisfy 0 <= producer_block < {self.compute_blocks}")
        if not _is_int(batch_start_work) or batch_start_work < 0:
            _fail("batch_start_work must be a non-negative integer")
        if batch_start_work % self.compute_blocks != producer_block:
            _fail("batch_start_work does not belong to producer_block")
        stride = self.compute_blocks * self.spec.batch_tiles
        if batch_start_work % stride != producer_block:
            _fail("batch_start_work is not aligned to a producer batch")
        return tuple(
            work_id
            for work_id in (
                batch_start_work + item * self.compute_blocks for item in range(self.spec.batch_tiles)
            )
            if work_id < self.tile_count
        )

    def producer_batches(self, producer_block: int) -> Iterator[Tuple[int, ...]]:
        if not _is_int(producer_block) or not 0 <= producer_block < self.compute_blocks:
            _fail(f"producer_block must satisfy 0 <= producer_block < {self.compute_blocks}")
        stride = self.compute_blocks * self.spec.batch_tiles
        for batch_start_work in range(producer_block, self.tile_count, stride):
            active = self.batch_work_items(producer_block, batch_start_work)
            if active:
                yield active

    def ready_key(self, batch_start_work: int, source: int, owner: int) -> ReadyKey:
        """Build a binary v1 ready key after validating its active producer batch."""
        if not _is_int(batch_start_work) or batch_start_work < 0:
            _fail("batch_start_work must be a non-negative integer")
        self._check_rank(source)
        self._check_rank(owner)
        producer_block = batch_start_work % self.compute_blocks
        active = self.batch_work_items(producer_block, batch_start_work)
        if not active:
            _fail("ready key cannot target an empty producer batch")
        if owner not in {self.owner_of_tile(self.work_to_tile(work)) for work in active}:
            _fail("owner has no produced tile in this batch, so no ready notification is legal")
        return ReadyKey(
            owner=owner,
            batch_start_work=batch_start_work,
            source=source,
            storage_index=batch_start_work * self.spec.nranks + source,
        )

    def notifications_for_batch(self, producer_block: int, batch_start_work: int, source: int) -> Tuple[ReadyKey, ...]:
        """One ready notification per owner, deduplicated within this batch."""
        self._check_rank(source)
        active = self.batch_work_items(producer_block, batch_start_work)
        owners = []
        for work_id in active:
            owner = self.owner_of_tile(self.work_to_tile(work_id))
            if owner not in owners:
                owners.append(owner)
        return tuple(self.ready_key(batch_start_work, source, owner) for owner in owners)

    def ready_for_tile(self, tile_id: int, source: int) -> ReadyKey:
        producer = self.producer_for_tile(tile_id, source)
        return self.ready_key(producer.batch_start_work, source, producer.owner)

    def _owner_interleaved_tiles(self) -> Tuple[int, ...]:
        """Tiles interleaved by owner and then owner-local ordinal.

        This derives only from ownership.  It is the RS compute order and is
        also the canonical global representation of the independent consumer
        order; it never treats a row-major work position as a tile ID.
        """
        lists = tuple(self.owner_tiles(owner) for owner in range(self.spec.nranks))
        longest = max((len(items) for items in lists), default=0)
        return tuple(
            lists[owner][owned_index]
            for owned_index in range(longest)
            for owner in range(self.spec.nranks)
            if owned_index < len(lists[owner])
        )

    def consumer_tile_order(self) -> Tuple[Tuple[int, int, int], ...]:
        """Global owner-interleaved order of ``(owner, owned_index, tile_id)``.

        This is an execution-order description only.  It does not change tile
        ownership or output layout.  For RS it interleaves contiguous-row owner
        lists, and consequently never assumes a consumer ordinal is a work ID.
        """
        return tuple(
            (self.owner_of_tile(tile_id), self.owned_index(tile_id), tile_id)
            for tile_id in self._owner_interleaved_tiles()
        )

    def consumer_for_lane(self, owner: int, comm_lane: int) -> Iterator[ConsumerAssignment]:
        """Owner-local persistent comm lane; emits no fake inactive tail slots."""
        self._check_rank(owner)
        if not _is_int(comm_lane) or not 0 <= comm_lane < self.spec.comm_blocks:
            _fail(f"comm_lane must satisfy 0 <= comm_lane < {self.spec.comm_blocks}")
        tiles = self.owner_tiles(owner)
        for consumer_iteration, owned_index in enumerate(range(comm_lane, len(tiles), self.spec.comm_blocks)):
            yield ConsumerAssignment(owner, owned_index, tiles[owned_index], comm_lane, consumer_iteration)

    def to_dict(self) -> dict[str, Any]:
        return {"spec": self.spec.to_dict(), "compute_blocks": self.compute_blocks}

    @classmethod
    def from_dict(cls, value: Mapping[str, Any]) -> "SchedulePlan":
        value = _strict_object(value, "SchedulePlan", ("spec", "compute_blocks"))
        return cls(spec=FusionSpec.from_dict(value["spec"]), compute_blocks=value["compute_blocks"])

    def to_json(self) -> str:
        return json.dumps(self.to_dict(), sort_keys=True, separators=(",", ":"), ensure_ascii=True)

    @classmethod
    def from_json(cls, value: str) -> "SchedulePlan":
        return cls.from_dict(_parse_json(value, "SchedulePlan"))
